#@title Figure 7: Fukui f- vs classical EAS preference
ARCHE = [("Furan","c1ccoc1","O",1), ("Thiophene","c1ccsc1","S",1),
         ("Pyrrole","c1cc[nH]c1","N",1), ("Pyridine","c1ccncc1","N",2)]
