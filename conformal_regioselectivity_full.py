    _ly = max(b.get_height()+0.012, (1-ALPHA)+0.022)
    ax.text(b.get_x()+b.get_width()/2, _ly, f"n={n}\n|set|={sm:.2f}", ha="center", va="bottom", fontsize=8.5)
